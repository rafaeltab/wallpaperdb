(async () => {
  const checks = [];
  const check = (name, ok) => { if (!ok) throw Error(name); checks.push(name); };
  const grid = document.getElementById('bin-grid');
  const cells = () => [...grid.children];
  const metric = document.getElementById('grid-metric');
  const change = value => { metric.value = value; metric.dispatchEvent(new Event('change')); };
  const scale = cell => Number(cell.firstChild.style.transform.match(/scale\((.+)\)/)[1]);
  const diagnosis = await (await fetch('/api/inspect', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ methodId: 'overlap-quality-dense', id: document.getElementById('inspector-title').textContent, query: { mode: 'vibe', targets: [{ color: '#ff0000' }] } }) })).json();
  const byId = new Map(diagnosis.regions.map(region => [String(region.index), region]));
  check('all 1024 identities preserved once', cells().length === 1024 && new Set(cells().map(c => c.dataset.index)).size === 1024);
  check('score is default', metric.value === 'score');
  check('zero contribution shrinks and positive contribution stands out', cells().every(c => Number(c.dataset.contribution) > 0 ? scale(c) > .22 : scale(c) === .22));
  check('native term contribution is used', cells().every(c => Math.abs(Number(c.dataset.contribution) - diagnosis.score.terms.filter(t => String(t.regionIndex) === c.dataset.index).reduce((sum, t) => sum + t.scoreContribution, 0)) < 1e-12));
  check('lightness rises within every hue column', cells().every((c, i, all) => i < 32 || byId.get(c.dataset.index).lab[0] >= byId.get(all[i - 32].dataset.index).lab[0]));
  const order = cells().map(c => c.dataset.index);
  const press = (position, key) => { const c = cells()[position]; c.click(); c.focus(); c.dispatchEvent(new KeyboardEvent('keydown', { key, bubbles: true })); return cells().indexOf(document.activeElement); };
  check('right follows visual order', press(100, 'ArrowRight') === 101);
  check('down follows visual row', press(100, 'ArrowDown') === 132);
  check('home follows visual row', press(100, 'Home') === 96);
  check('end follows visual row', press(100, 'End') === 127);
  check('top boundary preserves column', press(10, 'ArrowUp') === 10);
  check('bottom boundary preserves column', press(1000, 'ArrowDown') === 1000);
  check('one keyboard tab stop', cells().filter(c => c.tabIndex === 0).length === 1);
  change('coverage');
  check('coverage uses actual image presence', cells().every(c => byId.get(c.dataset.index).coverage > 0 ? scale(c) > .22 : scale(c) === .22));
  change('quality');
  check('quality uses conditional quality', cells().every(c => byId.get(c.dataset.index).conditionalQuality > 0 ? scale(c) > .22 : scale(c) === .22));
  change('color');
  check('all colors view fills every cell', cells().every(c => scale(c) === 1));
  check('display changes preserve color positions', JSON.stringify(order) === JSON.stringify(cells().map(c => c.dataset.index)));
  change('score');
  const tiny = cells().find(c => +c.dataset.contribution === 0);
  tiny.click();
  check('tiny cells still select the correct region', document.querySelector('#bin-detail h4').textContent.startsWith(`Region ${tiny.dataset.index} ·`) && tiny.getAttribute('aria-pressed') === 'true');
  const active = cells().find(c => +c.dataset.contribution > 0);
  active.click();
  check('tiny and active cells retain equal hit areas', Math.abs(tiny.getBoundingClientRect().width - active.getBoundingClientRect().width) < 1);
  check('desktop has no horizontal page overflow', document.documentElement.scrollWidth <= innerWidth);
  window.overlapGridQaOrder = order;
  return { checksPassed: checks.length, checks };
})()
